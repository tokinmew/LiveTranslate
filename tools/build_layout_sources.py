"""Generate the tiny text-resource catalog delivered by the 0.6.x source updater.

Older clients only accept Python/C# sources and three named documents. Keeping
this catalog in the dashboard source lets those clients bootstrap the organized
layout without a second executable, Python, a model download or a network call.
"""
import base64
import gzip
import hashlib
import json
from pathlib import Path
import sys


def generate(app):
    paths = sorted([*(p for name in ("scripts", "config", "docs")
                      for p in (app / name).iterdir() if p.is_file()), app / "quality/scan.ps1"])
    body = ["// Generated by tools/build_layout_sources.py from the actual distribution files.",
            "internal static class LayoutFiles", "{", "    internal static readonly string[][] Entries = {"]
    digest = hashlib.sha256()
    for path in paths:
        rel = path.relative_to(app).as_posix()
        data = path.read_bytes()
        sha = hashlib.sha256(data).hexdigest()
        digest.update((rel + "\0" + sha + "\n").encode())
        packed = base64.b64encode(gzip.compress(data, compresslevel=9, mtime=0)).decode("ascii")
        body.append("        new[] { " + ", ".join(map(json.dumps, (rel, sha, packed))) + " },")
    sources = sorted({p.relative_to(app).as_posix() for glob in ("ui/*.cs","backend/*.py")
                      for p in app.glob(glob)} | {"ui/LayoutFiles.cs"})
    body += ["    };", "    internal static readonly string[] SourcePaths = {"]
    body += ["        " + json.dumps(name) + "," for name in sources]
    body += ["    };", '    internal const string Fingerprint = "' + digest.hexdigest() + '";', "}"]
    (app / "ui/LayoutFiles.cs").write_bytes(("\n".join(body) + "\n").encode())


if __name__ == "__main__":
    generate(Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[1] / "LiveTranslate")
