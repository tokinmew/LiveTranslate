"""Embed a prior, signed Windows release for machines with no update history."""
import argparse
import base64
import hashlib
import json
from pathlib import Path
import sys
import textwrap
import zlib


def build(feed, output):
    backend = Path(__file__).resolve().parents[1] / "LiveTranslate" / "backend"
    sys.path.insert(0, str(backend))
    from release_signature import OFFICIAL, verify_official_manifest

    manifest = (feed / "latest.json").read_bytes()
    info = json.loads(manifest)
    verify_official_manifest(OFFICIAL, info)
    package = (feed / info["package"]).read_bytes()
    if len(package) != info["size"] or hashlib.sha256(package).hexdigest() != info["sha256"]:
        raise ValueError("The prior release package differs from its signed manifest.")
    encoded = base64.b64encode(zlib.compress(package, 9)).decode("ascii")
    lines = ['"""Generated by tools/build_feed_seed.py from a prior signed release."""',
             f"MANIFEST = {manifest!r}", "PACKAGE = ("]
    lines.extend('    b"' + line + '"' for line in textwrap.wrap(encoded, 112))
    content = ("\n".join([*lines, ")", ""])).encode("ascii")
    if len(content) > 1024 * 1024:
        raise ValueError("The embedded snapshot exceeds the updater's per-module limit.")
    output.write_bytes(content)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("feed", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    build(args.feed, args.output)
